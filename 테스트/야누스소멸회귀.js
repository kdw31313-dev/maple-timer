[0,450,900].forEach(t => imageAnalyzer.processJanusPresenceFrame(frame,t));
mode = 'ending';
[1350,1800,2250,2700].forEach(t => imageAnalyzer.processJanusPresenceFrame(frame,t));
assert.equal(alerts.length,0);
mode = 'absent';
[3150,3600,4050,4500,4950].forEach(t => imageAnalyzer.processJanusPresenceFrame(frame,t));
assert.equal(alerts.length,1);
assert.equal(alerts[0][1],'janus');
assert.equal(alerts[0][2].telegram,true);
mode = 'active';
[5400,5850,6300].forEach(t => imageAnalyzer.processJanusPresenceFrame(frame,t));
imageAnalyzer.reset();
assert.equal(imageAnalyzer.janusPresenceTracker.active,false);
console.log('야누스 상태·회색 위상·소멸·재사용·중단·텔레그램 요청 회귀 통과 (실제 전송은 모의 처리)');
